$ErrorActionPreference='Stop'
$taskProject=Split-Path $PSScriptRoot -Parent
$taskWorkspace=Split-Path $taskProject -Parent
$taskArtifacts=[IO.Path]::GetFullPath((Join-Path $taskWorkspace 'tmp\elo-brain-native-20261014'))
$taskSource=[IO.Path]::GetFullPath((Join-Path $taskArtifacts 'android-build-work\app-build\outputs\apk\debug\app-debug.apk'))
$taskPreserved=[IO.Path]::GetFullPath((Join-Path $taskArtifacts 'elo-brain-native-v8-20261015T0407.apk'))
$taskExpected='015aba1cd6341d7d40b593b69a0eb8ca859247c743f028fd10e8f6011db7a1de'
# Exact file removal only, inside this execution's verified build output. Never
# recurse through a workspace, dependency installation, source, backup or session.
if(-not $taskSource.StartsWith($taskArtifacts+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)) {throw 'OUTSIDE_OWN_ARTIFACTS'}
if((Get-Item -LiteralPath $taskSource).Attributes -band [IO.FileAttributes]::ReparsePoint) {throw 'REPARSE_TARGET_REFUSED'}
if((Get-FileHash -LiteralPath $taskSource -Algorithm SHA256).Hash.ToLowerInvariant() -ne $taskExpected -or
 (Get-FileHash -LiteralPath $taskPreserved -Algorithm SHA256).Hash.ToLowerInvariant() -ne $taskExpected) {throw 'PRESERVED_COPY_MISMATCH'}
$taskProcesses=@(Get-CimInstance Win32_Process | Where-Object {
 $_.Name -match '^(java|aapt2|gradle|kotlinc)\.exe$' -or
 $_.Name -eq 'adb.exe' -and $_.CommandLine -match '\binstall\b' -or
 $_.Name -eq 'node.exe' -and $_.CommandLine -match 'inspect-native-apk|app-debug\.apk'
})
if($taskProcesses.Count -gt 0){throw 'BUILD_OR_APK_CONSUMER_ACTIVE'}
$taskProbe=[IO.File]::Open($taskSource,[IO.FileMode]::Open,[IO.FileAccess]::Read,[IO.FileShare]::None)
$taskProbe.Dispose()
$taskDrive=[IO.DriveInfo]::new('C:\')
$taskBefore=$taskDrive.AvailableFreeSpace
$taskBytes=(Get-Item -LiteralPath $taskSource).Length
$taskStamp=[DateTime]::UtcNow.ToString('yyyyMMddTHHmmssfff')
$taskReport=Join-Path $taskArtifacts ('selective-cleanup-'+$taskStamp+'.json')
$taskRecord=[ordered]@{atUtc=[DateTime]::UtcNow.ToString('o');spaceBefore=$taskBefore;approvedExactPath=$taskSource;bytes=$taskBytes;sha256=$taskExpected;preservedCopy=$taskPreserved;preservedCopyVerified=$true;activeBuildConsumers=$taskProcesses.Count;exclusiveReadProbe=$true;reason='Redundant generated APK output with an exact separately preserved V8 copy. Regenerated by assembleDebug.';sourceDeleted=$false;backupsDeleted=$false;phoneDataTouched=$false;deleted=$false}
# Write the reviewed path before mutation, as requested by the user.
$taskRecord | ConvertTo-Json | Set-Content -LiteralPath $taskReport -Encoding utf8
Remove-Item -LiteralPath $taskSource -ErrorAction Stop
if((Get-FileHash -LiteralPath $taskPreserved -Algorithm SHA256).Hash.ToLowerInvariant() -ne $taskExpected){throw 'PRESERVED_COPY_CHANGED'}
$taskRecord.deleted=$true
$taskRecord.spaceAfter=$taskDrive.AvailableFreeSpace
$taskRecord.observedFreeSpaceIncrease=$taskRecord.spaceAfter-$taskBefore
$taskRecord | ConvertTo-Json | Set-Content -LiteralPath $taskReport -Encoding utf8
[ordered]@{report=$taskReport;verifiedRedundantBytesRemoved=$taskBytes;spaceBefore=$taskBefore;spaceAfter=$taskRecord.spaceAfter;preservedCopyVerified=$true;sourceDeleted=$false;backupsDeleted=$false} | ConvertTo-Json
